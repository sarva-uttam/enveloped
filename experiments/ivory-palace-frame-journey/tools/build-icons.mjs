// Generates components/icons.js from the project's existing icon system
// (lucide-react, ISC) so the plain-HTML experiment can use the same icons
// as inline, code-native SVG without a bundler or a new dependency.
// Usage (from the repo root): node experiments/ivory-palace-frame-journey/tools/build-icons.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "../../../package.json"));
const pkg = require("lucide-react/package.json");
const iconsDir = join(dirname(require.resolve("lucide-react/package.json")), "dist/esm/icons");
const NAMES = ["music", "volume-2", "image", "share-2", "chevron-up", "chevron-down", "map-pin", "calendar-days", "calendar-plus", "download"];

const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const out = {};
for (const name of NAMES) {
  const { __iconNode } = await import(pathToFileURL(join(iconsDir, `${name}.mjs`)).href);
  out[name] = __iconNode.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${esc(v)}"`).join(" ")}/>`).join("");
}
const file = `/*
 * GENERATED by tools/build-icons.mjs — do not edit by hand.
 * Icon geometry from lucide-react v${pkg.version} (ISC licence, the project's
 * existing icon system). Rendered as inline SVG: code-native, no rasters.
 */
(function () {
  "use strict";
  var NODES = ${JSON.stringify(out, null, 2)};
  window.EnvelopedIcons = {
    names: Object.keys(NODES),
    svg: function (name, size) {
      if (!NODES[name]) throw new Error("Unknown icon: " + name);
      var s = size || 20;
      return '<svg class="env-icon env-icon--' + name + '" xmlns="http://www.w3.org/2000/svg" width="' + s + '" height="' + s +
        '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
        NODES[name] + "</svg>";
    }
  };
})();
`;
writeFileSync(join(here, "../components/icons.js"), file);
console.log("wrote components/icons.js:", NAMES.join(", "));
